# Crie um programa que leia quanto dinheiro uma pessoa tem na carteira e mostre quantos dólares ela pode comprar.

print("\033[34mConvertendo R$ em U$\033[m")

real = float(input("Quantos reais você possui em sua carteira \033[34mR$\033[m"))

dollar = real / 5.35

print(f"\nEssa quantia equivale á \033[34mU${dollar:.2f}\033[m")


# Dóllar em 27/10/2026 5,35 Real brasileiro